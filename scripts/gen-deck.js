// ── Помощники ───────────────────────────────────────────────────────────────
function dark() {
  const s = p.addSlide();
  s.background = { color: BG };
  return s;
}

/** Жёлтый круг с номером — мотив, повторяется на каждом разделе. */
function badge(s, n, x, y) {
  s.addShape(p.ShapeType.ellipse, {
    x, y, w: 0.46, h: 0.46, fill: { color: ACC },
  });
  s.addText(String(n), {
    x, y, w: 0.46, h: 0.46, align: "center", valign: "middle",
    fontFace: TITLE_F, fontSize: 15, bold: true, color: "17170F", margin: 0,
  });
}

function heading(s, text, x, y, w, size = 26) {
  s.addText(text, {
    x, y, w, h: 0.62, fontFace: TITLE_F, fontSize: size, bold: true,
    color: TEXT, charSpacing: -0.4, margin: 0, valign: "middle",
  });
}

function kicker(s, text, x, y) {
  s.addText(text.toUpperCase(), {
    x, y, w: 6, h: 0.26, fontFace: BODY_F, fontSize: 10, bold: true,
    color: ACC, charSpacing: 1.6, margin: 0,
  });
}

function bullets(s, items, opts) {
  s.addText(
    items.map((t, i) => ({
      text: t,
      options: { bullet: { indent: 14 }, breakLine: i !== items.length - 1 },
    })),
    Object.assign(
      {
        fontFace: BODY_F, fontSize: 12.5, color: DIM, lineSpacing: 17,
        paraSpaceAfter: 7, margin: 0, valign: "top",
      },
      opts,
    ),
  );
}

/** Плашка «Важно знать» — тёплая подложка, без полосок по краю. */
function rules(s, items, x, y, w, h) {
  s.addShape(p.ShapeType.roundRect, {
    x, y, w, h, fill: { color: "2A211A" }, rectRadius: 0.06,
    line: { color: "4A3A28", width: 0.75 },
  });
  s.addText("ВАЖНО ЗНАТЬ", {
    x: x + 0.22, y: y + 0.12, w: w - 0.44, h: 0.22,
    fontFace: BODY_F, fontSize: 8.5, bold: true, color: WARN, charSpacing: 1.4, margin: 0,
  });
  s.addText(
    items.map((t, i) => ({
      text: t,
      options: { bullet: { indent: 12 }, breakLine: i !== items.length - 1 },
    })),
    {
      x: x + 0.22, y: y + 0.36, w: w - 0.44, h: h - 0.5,
      fontFace: BODY_F, fontSize: 10.5, color: WARN, lineSpacing: 14,
      paraSpaceAfter: 4, margin: 0, valign: "top",
    },
  );
}

