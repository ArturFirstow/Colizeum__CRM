#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────────────────────
# Обновление боевого сервиса. Запускать НА СЕРВЕРЕ из папки проекта:
#
#     ./scripts/deploy.sh                 — обновить до свежего кода рабочей ветки
#     ./scripts/deploy.sh имя-ветки       — обновить до другой ветки
#     ./scripts/deploy.sh --dry           — только показать, что приедет, и проверить сервер
#
# Порядок такой, чтобы сайт не ломался:
#   1. проверки сервера (место, память, настройки) — до того, как что-то менять;
#   2. показ, что именно приедет;
#   3. резервная копия и проверка, что она ДЕЙСТВИТЕЛЬНО создалась;
#   4. запоминаем текущую версию — чтобы откатиться одной командой;
#   5. код → зависимости → схема базы → сборка → перезапуск;
#   6. проверка, что сайт отвечает. Не отвечает — печатаем команду откета.
#
# ⚠️ Скрипт НИКОГДА не выполняет сид: он стирает базу. Сид — только один раз,
# при самом первом запуске, вручную.
# ─────────────────────────────────────────────────────────────────────────────
set -euo pipefail

cd "$(dirname "$0")/.."
APP_DIR="$(pwd)"
PORT="${PORT:-3000}"

# Ветка, из которой живёт боевой сайт. Менять здесь, а не в голове.
#
# ⚠️ Раньше по умолчанию стояла ветка, с которой сайт поднимали в августе.
# Работа ушла далеко вперёд, а ниже стоит `git reset --hard` — запуск без имени
# ветки откатил бы сервис на месяцы назад. Отсюда и ветка по умолчанию, и
# проверка «а не назад ли мы?».
DEFAULT_BRANCH="claude/deploy-site-timeweb-domain-2m5dhk"
BRANCH="$DEFAULT_BRANCH"
DRY=0
for arg in "$@"; do
  case "$arg" in
    --dry|--check) DRY=1 ;;
    -*) echo "Неизвестный ключ: $arg"; exit 2 ;;
    *) BRANCH="$arg" ;;
  esac
done

say()  { printf '\n\033[1m%s\033[0m\n' "$1"; }
ok()   { printf '  \033[32m✓\033[0m %s\n' "$1"; }
warn() { printf '  \033[33m!\033[0m %s\n' "$1"; }
bad()  { printf '  \033[31m✗\033[0m %s\n' "$1"; }

# ── 1. Проверки сервера ──────────────────────────────────────────────────────
# Делаются ДО любых изменений: если на диске нет места или в .env нет ключа,
# лучше узнать это сейчас, а не на середине сборки с лежащим сайтом.
say "Проверяю сервер"
STOP=0

# Свои правки в коде: `git reset --hard` ниже снесёт их молча.
if [ -n "$(git status --porcelain 2>/dev/null)" ]; then
  warn "в папке есть изменённые файлы — обновление их СНЕСЁТ:"
  git status --porcelain | head -5 | sed 's/^/        /'
  warn "если это нужные правки, сохраните их (git stash) и запустите снова"
fi

# Место на диске: сборке нужно примерно 1,5 ГБ (node_modules + .next).
FREE_MB=$(df -Pk "$APP_DIR" | awk 'NR==2 {print int($4/1024)}')
if [ "$FREE_MB" -lt 1500 ]; then
  bad "на диске свободно ${FREE_MB} МБ — сборке нужно около 1500 МБ"
  echo "        Освободить: npm cache clean --force; rm -rf .next; apt clean"
  STOP=1
else
  ok "место на диске: ${FREE_MB} МБ свободно"
fi

# Память: `next build` на 1 ГБ без подкачки падает и роняет сборку, а иногда и
# работающий процесс. Лучше заранее сказать про swap.
MEM_AVAIL_MB=$(awk '/MemAvailable/ {print int($2/1024)}' /proc/meminfo 2>/dev/null || echo 0)
SWAP_MB=$(awk '/SwapTotal/ {print int($2/1024)}' /proc/meminfo 2>/dev/null || echo 0)
if [ "$MEM_AVAIL_MB" -lt 1200 ] && [ "$SWAP_MB" -lt 512 ]; then
  warn "свободной памяти ${MEM_AVAIL_MB} МБ, подкачки нет — сборка может не уложиться"
  echo "        Добавить 2 ГБ подкачки (один раз, безопасно):"
  echo "        fallocate -l 2G /swapfile && chmod 600 /swapfile && mkswap /swapfile && swapon /swapfile"
  echo "        echo '/swapfile none swap sw 0 0' >> /etc/fstab"
else
  ok "память: ${MEM_AVAIL_MB} МБ свободно, подкачка ${SWAP_MB} МБ"
fi

# Node: Next.js 15 требует минимум 18.18, проверено на 20 и 22.
NODE_MAJOR=$(node -v 2>/dev/null | sed 's/^v\([0-9]*\).*/\1/' || echo 0)
if [ "${NODE_MAJOR:-0}" -lt 18 ]; then
  bad "Node $(node -v 2>/dev/null || echo 'не найден') — нужен хотя бы 18"
  STOP=1
else
  ok "Node $(node -v)"
fi

# Настройки: без этих двух сервис не поднимется вообще.
if [ ! -f .env ]; then
  bad "нет файла .env — сервис не запустится"
  STOP=1
else
  for key in DATABASE_URL AUTH_SECRET; do
    if grep -qE "^${key}=" .env; then ok ".env: $key на месте"; else bad ".env: нет $key"; STOP=1; fi
  done
  # Эти не обязательны, но без них часть сервиса молча не работает.
  grep -qE '^TELEGRAM_BOT_TOKEN=' .env || warn ".env: нет TELEGRAM_BOT_TOKEN — уведомления в Telegram не придут (docs/TELEGRAM.md)"
  grep -qE '^AI_API_KEY=' .env        || warn ".env: нет AI_API_KEY — напарник ИИ и саммари не работают"
  grep -qE '^BACKUP_PASSPHRASE=' .env || warn ".env: нет BACKUP_PASSPHRASE — резервные копии будут НЕзашифрованными (требование 6.5)"

  # Склейка двух настроек в одной строке. Так бывает, когда переменную
  # дописывают командой `echo … >> .env`, а файл не заканчивается переводом
  # строки: новая настройка прилипает к предыдущей, файл перестаёт читаться и
  # сервис падает с Internal Server Error на ровном месте.
  #
  # ⚠️ Проверять «строка начинается с ИМЯ=» бесполезно: склеенная строка этому
  # условию как раз удовлетворяет (`AUTH_SECRET="x"BACKUP_PASSPHRASE="y"`).
  # Ищем ВТОРОЕ имя настройки в середине строки: такие пишутся заглавными.
  # Это подсказка, а не приговор — значение вполне может содержать «ЧТО_ТО=»,
  # поэтому предупреждаем, но обновление не останавливаем.
  GLUED="$(grep -nE '^[A-Za-z_][A-Za-z0-9_]*=.*[A-Z][A-Z0-9_]{3,}=' .env | cut -d: -f1 | tr '\n' ' ' || true)"
  if [ -n "${GLUED// /}" ]; then
    warn ".env: в строке ${GLUED% }, возможно, слиплись две настройки"
    echo "        Так выходит, когда переменную дописали командой с >> в конец файла."
    echo "        Проверьте: nano .env — каждая настройка должна быть на своей строке."
  fi

  # Причина склейки — файл без перевода строки в конце. Ловим ДО того, как
  # кто-нибудь допишет туда переменную и уронит сервис.
  if [ -n "$(tail -c 1 .env)" ]; then
    warn ".env не заканчивается переводом строки"
    echo "        Допишете сюда настройку — она слипнется с последней, и сервис упадёт."
    echo "        Поправить сейчас (безопасно): printf '\\n' >> .env"
  fi
fi

if [ "$STOP" = "1" ]; then
  echo
  echo "⛔ Обновление не начато: сначала исправьте помеченное ✗. Сайт работает как работал."
  exit 1
fi

# ── 2. Что именно приедет ────────────────────────────────────────────────────
say "Смотрю, что приедет из ветки $BRANCH"
git fetch origin "$BRANCH" --quiet
HERE="$(git rev-parse HEAD)"
THERE="$(git rev-parse "origin/$BRANCH")"

if [ "$HERE" = "$THERE" ]; then
  ok "на сервере уже самый свежий код — обновлять нечего"
  [ "$DRY" = "1" ] && exit 0
  echo "  (пересборка всё равно будет выполнена)"
else
  COUNT="$(git rev-list --count "$HERE..$THERE")"
  ok "новых правок: $COUNT"
  git log --format='        • %s' "$HERE..$THERE" | head -50
  [ "$COUNT" -gt 50 ] && echo "        … и ещё $((COUNT - 50)) — полный список: npm run release:notes"
fi

# Заслон от случайного откета: если на сервере есть коммиты, которых в целевой
# ветке нет, значит мы собираемся поехать НАЗАД. Такое бывает только по ошибке
# (не та ветка в команде), а цена ошибки — сайт месячной давности.
BEHIND="$(git rev-list --count "origin/$BRANCH..HEAD" || echo 0)"
if [ "$BEHIND" != "0" ]; then
  echo
  echo "⚠️  ВНИМАНИЕ: на сервере сейчас $BEHIND коммит(ов), которых в ветке $BRANCH нет."
  echo "    Это не обновление, а ОТКАТ НАЗАД: всё, что сделано после, исчезнет из кода."
  echo "    Чаще всего причина простая — указана не та ветка."
  echo
  if [ "$DRY" = "1" ]; then
    echo "    (проверка, ничего не меняю)"
  elif [ "${FORCE_ROLLBACK:-}" = "1" ]; then
    echo "    FORCE_ROLLBACK=1 — продолжаю, раз вы так решили."
  else
    printf "    Если откат нужен осознанно, напишите «да» и Enter: "
    read -r ANSWER
    [ "$ANSWER" = "да" ] || { echo "Отменено. Ничего не изменилось."; exit 1; }
  fi
fi

if [ "$DRY" = "1" ]; then
  echo
  if [ "$BEHIND" != "0" ]; then
    # Не предлагаем «обновить» то, что на деле откатит сайт назад.
    echo "⚠️  Сервер к работе готов, но ветка выбрана неудачно: обновление до"
    echo "    «$BRANCH» откатит сайт назад на $BEHIND правок."
    echo "    Рабочая ветка сайта: $DEFAULT_BRANCH"
    echo "    Обновить до неё: ./scripts/deploy.sh"
    exit 1
  fi
  echo "✅ Проверка пройдена. Сервер к обновлению готов, ничего не изменено."
  if [ "$BRANCH" = "$DEFAULT_BRANCH" ]; then
    echo "   Обновить: ./scripts/deploy.sh"
  else
    echo "   Обновить: ./scripts/deploy.sh $BRANCH"
  fi
  exit 0
fi

# ── 3. Резервная копия — и проверка, что она есть ────────────────────────────
# Раньше второй скрипт обновления делал копию «как получится» и шёл дальше.
# Обновление без копии — единственный шаг, после которого ошибку уже не отменить.
say "Резервная копия базы и файлов"
BACKUP_DIR="${BACKUP_DIR:-/var/backups/colizeum}"
# Запускаем ЯВНО, а не полагаясь на `set -e`: иначе скрипт копии, упавший на
# мелочи, обрывает обновление молча — человек видит вывод копии, потом сразу
# приглашение командной строки и думает, что всё прошло. Ровно так и случилось
# на боевом сервере 12 октября.
if ! bash deploy/backup.sh; then
  echo
  bad "скрипт резервной копии завершился ошибкой — обновление остановлено"
  echo "        Сайт продолжает работать на прежнем коде, ничего не изменено."
  echo "        Посмотрите сообщение выше и запустите копию отдельно: bash deploy/backup.sh"
  exit 1
fi
# `-mmin -10` вместо `-newermt`: не зависит от разбора словесных дат.
FRESH="$(find "$BACKUP_DIR" -maxdepth 1 -name 'db_*' -mmin -10 2>/dev/null | head -1)"
if [ -z "$FRESH" ]; then
  echo
  bad "свежей копии базы в $BACKUP_DIR нет — обновление остановлено"
  echo "        Разберитесь с копией и запустите снова: bash deploy/backup.sh"
  exit 1
fi
ok "копия на месте: $FRESH"

# ── 4. Куда откатываться, если что ───────────────────────────────────────────
echo "$HERE" > .deploy-prev
ok "текущая версия запомнена: ${HERE:0:7} (откат — ./scripts/rollback.sh)"

# ── 5. Обновление ────────────────────────────────────────────────────────────
say "Забираю код"
git reset --hard "origin/$BRANCH"

say "Ставлю зависимости"
npm ci

say "Обновляю схему базы (данные сохраняются)"
npx prisma generate
# Обычный push данные не трогает. Но если обновление требует УДАЛИТЬ столбец,
# в котором что-то лежит, Prisma останавливается и просит подтверждения — и в
# своей подсказке предлагает в том числе `--force-reset`, то есть «стереть базу
# целиком». Человек, читающий это впервые, может так и сделать. Поэтому ловим
# такой случай сами и объясняем словами.
if ! npx prisma db push; then
  echo
  echo "⛔ Схема базы не обновилась. ДАННЫЕ ЦЕЛЫ, сайт продолжает работать на"
  echo "   прежнем коде — скрипт остановился до сборки и перезапуска."
  echo
  echo "   Прочитайте текст Prisma выше. Дальше два случая:"
  echo
  echo "   1) «You are about to drop the column …» — обновление хочет убрать"
  echo "      столбец, который больше не нужен. Если это ожидаемо (мы убирали"
  echo "      такие столбцы осознанно — например, старые before/after в журнале"
  echo "      действий, где лежали значения полей), подтвердите один раз:"
  echo "          npx prisma db push --accept-data-loss"
  echo "      и запустите обновление снова: ./scripts/deploy.sh"
  echo
  echo "   2) «it is not possible to execute this step» — в схеме появился"
  echo "      обязательный столбец без значения по умолчанию. Это НАША ошибка в"
  echo "      коде, а не ваша. НЕ запускайте --force-reset: он стирает базу."
  echo "      Напишите об этой строке — поправим схему."
  echo
  exit 1
fi

say "Собираю"
npm run build

say "Перезапускаю"
pm2 restart colizeum --update-env || pm2 start deploy/ecosystem.config.cjs

# ── 6. Проверка, что сайт действительно поднялся ─────────────────────────────
say "Проверяю, что сайт отвечает"
UP=0
for _ in $(seq 1 20); do
  CODE="$(curl -s -o /dev/null -w '%{http_code}' --max-time 5 "http://127.0.0.1:$PORT/login" || true)"
  if [ "$CODE" = "200" ] || [ "$CODE" = "307" ] || [ "$CODE" = "302" ]; then UP=1; break; fi
  sleep 3
done

if [ "$UP" = "1" ]; then
  ok "страница входа отвечает"
else
  echo
  bad "сайт не отвечает на порту $PORT в течение минуты"
  echo
  echo "   Что сделать по порядку:"
  echo "     1) посмотреть причину:   pm2 logs colizeum --lines 50"
  echo "     2) если непонятно — вернуть прежнюю версию:  ./scripts/rollback.sh"
  echo "        (откат только кода; база и файлы остаются как есть)"
  echo
  exit 1
fi

# Полный отчёт по серверу — он же проверяет сертификат, диск и свежесть копий.
bash deploy/healthcheck.sh || true

echo
echo "✅ Обновление завершено. Версия: $(git rev-parse --short HEAD) — $(git log -1 --format=%s)"
echo
echo "Если после крупного обновления что-то выглядит странно:"
echo "  • стадии сделок из прежней воронки переводятся командой: npm run stages:migrate"
echo "  • вернуть прежнюю версию кода:                            ./scripts/rollback.sh"
echo "  • журнал приложения:                                      pm2 logs colizeum --lines 50"
