#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────────────────────
# Обновление боевого сервиса на сервере. Запускать НА СЕРВЕРЕ из папки проекта:
#
#     ./scripts/deploy.sh
#
# Что делает: забирает свежий код из GitHub, ставит зависимости, обновляет
# схему базы (данные при этом сохраняются), пересобирает и перезапускает.
# Сайт лежит несколько секунд на шаге перезапуска — это нормально.
#
# ⚠️ Скрипт НИКОГДА не выполняет сид: он стирает базу. Сид — только один раз,
# при самом первом запуске, вручную.
# ─────────────────────────────────────────────────────────────────────────────
set -euo pipefail

# Ветка, из которой живёт боевой сайт. Менять здесь, а не в голове.
#
# ⚠️ Раньше здесь по умолчанию стояла ветка `claude/service-blueprint-frontend-ref797`
# — та, с которой сайт поднимали в августе. С тех пор работа ушла далеко вперёд,
# и запуск `./scripts/deploy.sh` без имени ветки откатил бы сервис на несколько
# месяцев назад (ниже стоит `git reset --hard`, он сносит всё молча). Поэтому
# ветка по умолчанию — рабочая, а ниже добавлена проверка «а не назад ли мы?».
BRANCH="${1:-claude/deploy-site-timeweb-domain-2m5dhk}"
cd "$(dirname "$0")/.."

echo "▸ Резервная копия базы и файлов…"
./scripts/backup.sh

echo "▸ Забираю свежий код из ветки $BRANCH…"
git fetch origin "$BRANCH"

# Заслон от случайного откета: если на сервере есть коммиты, которых в целевой
# ветке нет, значит мы собираемся поехать НАЗАД. Такое бывает только по ошибке
# (не та ветка в команде), а цена ошибки — сайт месячной давности.
BEHIND="$(git rev-list --count "origin/$BRANCH..HEAD" || echo 0)"
if [ "$BEHIND" != "0" ]; then
  echo
  echo "⚠️  ВНИМАНИЕ: на сервере сейчас $BEHIND коммит(ов), которых в ветке $BRANCH нет."
  echo "    Это не обновление, а ОТКАТ НАЗАД: всё, что сделано после, исчезнет из кода."
  echo "    Чаще всего причина простая — указана не та ветка."
  echo
  if [ "${FORCE_ROLLBACK:-}" = "1" ]; then
    echo "    FORCE_ROLLBACK=1 — продолжаю, раз вы так решили."
  else
    printf "    Если откат нужен осознанно, напишите «да» и Enter: "
    read -r ANSWER
    [ "$ANSWER" = "да" ] || { echo "Отменено. Ничего не изменилось."; exit 1; }
  fi
fi

git reset --hard "origin/$BRANCH"

echo "▸ Ставлю зависимости…"
npm ci

echo "▸ Обновляю схему базы (данные сохраняются)…"
npx prisma generate
npx prisma db push

echo "▸ Собираю…"
npm run build

echo "▸ Перезапускаю…"
pm2 restart colizeum --update-env || pm2 start npm --name colizeum -- start

echo
echo "✅ Готово. Открывайте сайт и проверяйте."
echo "   Если что-то пошло не так — журнал: pm2 logs colizeum --lines 50"
