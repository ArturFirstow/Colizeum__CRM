def plain(fragment: str) -> str:
    """HTML → обычный текст одной строкой."""
    fragment = re.sub(r"<br\s*/?>", " ", fragment)
    fragment = re.sub(r"<[^>]+>", "", fragment)
    return html.unescape(re.sub(r"\s+", " ", fragment)).strip()


def short(text: str, limit: int = 260) -> str:
    """Короткая выжимка: обрезаем по границе предложения, а не посреди слова."""
    text = text.strip()
    if len(text) <= limit:
        return text
    cut = text[:limit]
    for sep in (". ", "; ", ", "):
        pos = cut.rfind(sep)
        if pos > limit * 0.5:
            return cut[: pos + 1].strip()
    return cut.rsplit(" ", 1)[0] + "…"


def parse_register() -> tuple[list[dict], str]:
    src = REGISTER.read_text(encoding="utf-8")
    css = re.search(r"<style>(.*?)</style>", src, re.S).group(1)
    body = src.split("<!-- ============ ОБЩИЙ ПЕРЕЧЕНЬ", 1)[1]

    rows: list[dict] = []
    section = ""
    for part in re.split(r"(<h2>.*?</h2>|<h3>.*?</h3>)", body, flags=re.S):
        if part.startswith("<h2>") or part.startswith("<h3>"):
            section = plain(part)
            continue
        for tr in re.findall(r"<tr>(.*?)</tr>", part, re.S):
            if "<th" in tr:
                continue
            status = re.search(r'class="st (s-\w+)"', tr)
            if not status:
                continue
            cells = re.findall(r"<td[^>]*>(.*?)</td>", tr, re.S)
            if len(cells) < 3:
                continue
            num = plain(cells[0]) if 'class="num"' in tr else ""
            title = plain(cells[1]) if num else plain(cells[0])
            proof = plain(cells[-1])
            rows.append(
                {
                    "section": section,
                    "num": num,
                    "title": title,
                    "cls": status.group(1),
                    "proof": proof,
                }
            )
    return rows, css


def esc(text: str) -> str:
    return html.escape(text, quote=False)


def status_cell(cls: str) -> str:
    return f'<span class="st {cls}">{STATUS_LABEL[cls]}</span>'


