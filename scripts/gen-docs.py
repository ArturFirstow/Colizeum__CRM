def img(name):
    path = os.path.join(SHOTS, name + ".jpg")
    if not os.path.exists(path):
        return ""
    b64 = base64.b64encode(open(path, "rb").read()).decode()
    return f'<img src="data:image/jpeg;base64,{b64}" alt="" loading="lazy">'

