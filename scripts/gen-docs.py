# ─────────────────────────────────────────────────────────────────────────────

def section_html(anchor, title, shot, lead, points, rules):
    parts = [f'<section id="{anchor}">', f'<h2>{title}</h2>', f'<p class="lead">{lead}</p>']
    if shot:
        parts.append(f'<figure>{img(shot)}</figure>')
    if points:
        parts.append('<h3>Что здесь можно</h3><ul>')
        for p in points:
            parts.append(f'<li>{p}</li>')
        parts.append('</ul>')
    for extra in EXTRA_SHOTS.get(anchor, []):
        parts.append(f'<figure>{img(extra)}</figure>')
    if rules:
        parts.append('<div class="rules"><b>Важно знать</b><ul>')
        for r in rules:
            parts.append(f'<li>{r}</li>')
        parts.append('</ul></div>')
    parts.append('</section>')
    return "\n".join(parts)


