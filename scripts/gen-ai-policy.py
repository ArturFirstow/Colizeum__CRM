def esc(s: str) -> str:
    return s


def count(items):
    из = {}
    for it in items:
        из[it["status"]] = из.get(it["status"], 0) + 1
    return из


def git_rev() -> str:
    try:
        return subprocess.check_output(["git", "rev-parse", "--short", "HEAD"],
                                       text=True).strip()
    except Exception:
        return "—"


def item_html(it) -> str:
    have = "".join(f"<li>{esc(x)}</li>" for x in it["have"])
    todo = "".join(f"<li>{esc(x)}</li>" for x in it["todo"])
    blocks = []
    if have:
        blocks.append(f'<div class="col"><h5>Что есть в сервисе</h5><ul>{have}</ul></div>')
    if todo:
        blocks.append(f'<div class="col todo"><h5>Что осталось</h5><ul>{todo}</ul></div>')
    if not blocks:
        blocks.append('<div class="col"><h5>Что есть в сервисе</h5><ul><li>Ничего не сделано.</li></ul></div>')
    return f"""
    <article class="item {it['status']}">
      <div class="head">
        <span class="code">{it['code']}</span>
        <h4>{esc(it['title'])}</h4>
        <span class="badge {it['status']}">{LABEL[it['status']]}</span>
      </div>
      <div class="cols">{''.join(blocks)}</div>
      <div class="who">Кто решает: {esc(it['who'])}</div>
    </article>"""


