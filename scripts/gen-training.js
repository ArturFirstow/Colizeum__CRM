  String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

function img(name) {
  const file = fs.existsSync(pageShot(name)) ? pageShot(name) : deckShot(name);
  if (!fs.existsSync(file)) return "";
  const b64 = fs.readFileSync(file).toString("base64");
  return `<img src="data:image/jpeg;base64,${b64}" alt="" loading="lazy">`;
}

