// ─────────────────────────────────────────────────────────────────────────────
// Метка тестового контура (требования 6.2 и 9.5).
//
// Тестовая и боевая среды должны быть разделены — но разделение, которого не
// видно, не работает: человек открывает похожий экран, вносит правку и только
// потом понимает, что был не там. Поэтому на тестовом контуре через всю
// страницу идёт полоса, которую нельзя не заметить и нельзя закрыть.
//
// Включается переменной APP_ENV=staging в .env тестового сервера. На боевом её
// нет — значит и полосы нет, ничего настраивать не нужно.
// ─────────────────────────────────────────────────────────────────────────────

export function isStaging(): boolean {
  return (process.env.APP_ENV ?? "").toLowerCase() === "staging";
}

export function StagingBanner() {
  if (!isStaging()) return null;
  return (
    <div className="sticky top-0 z-[60] flex flex-wrap items-center justify-center gap-x-3 gap-y-0.5 bg-amber-400 px-4 py-1.5 text-center text-xs font-semibold text-ink-950">
      <span>⚠ ТЕСТОВЫЙ КОНТУР</span>
      <span className="font-normal">
        Данные здесь вымышленные. Настоящие клиенты и документы — на боевом адресе.
      </span>
    </div>
  );
}
