import Link from "next/link";

// ─────────────────────────────────────────────────────────────────────────────
// Строка со ссылкой на политику там, где собираются данные о людях
// (требование 4.3: «политика опубликована, ссылка на КАЖДОЙ странице, где
// собираются данные»).
//
// Политика и раньше была опубликована, но ссылка на неё стояла только в
// подвале и под меню профиля. Требование просит иначе: человек, который прямо
// сейчас вводит чужие ФИО и телефон, должен видеть, по каким правилам эти
// данные будут обрабатываться, — в этот самый момент, а не когда-нибудь.
//
// Намеренно одна тихая строка: это подпись под формой, а не предупреждение.
// Громкая плашка над каждым полем ввода читалась бы как ошибка и мешала работе.
// ─────────────────────────────────────────────────────────────────────────────

export function PrivacyNote({ what }: { what?: string }) {
  return (
    <p className="text-xs leading-snug text-ink-500">
      {what ?? "Здесь вводятся данные о человеке"} — они обрабатываются по{" "}
      <Link
        href="/legal/politika"
        target="_blank"
        className="underline underline-offset-2 transition hover:text-brand"
      >
        политике обработки персональных данных
      </Link>
      . Вводите только то, что нужно для работы.
    </p>
  );
}
