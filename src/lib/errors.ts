// ─────────────────────────────────────────────────────────────────────────────
// Ошибки, текст которых МОЖНО показывать человеку.
//
// Раньше любая внутренняя ошибка уходила в браузер своим текстом. В нём
// попадаются пути к файлам на сервере, куски запросов к базе и имена колонок —
// подсказка для того, кто ищет, за что зацепиться. Требование: пользователь
// видит «Что-то пошло не так», подробности остаются в журнале сервера.
//
// Но часть ошибок написана специально для человека и помогает ему починить
// дело самому («откройте доступ к таблице»). Такие заворачиваем в PublicError —
// только их текст и доходит до браузера.
// ─────────────────────────────────────────────────────────────────────────────

export class PublicError extends Error {
  readonly code: string;
  readonly status: number;

  constructor(message: string, options?: { code?: string; status?: number }) {
    super(message);
    this.name = "PublicError";
    this.code = options?.code ?? "request_failed";
    this.status = options?.status ?? 400;
  }
}
