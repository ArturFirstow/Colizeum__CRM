#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────────────────────
# Обновление сервиса — ОДНО на весь проект: scripts/deploy.sh.
#
# Этот файл оставлен переходником: на него ссылаются старые записи и привычка.
# Раньше он был вторым, самостоятельным сценарием обновления, и отличался от
# основного в опасную сторону:
#
#   • делал `bash deploy/backup.sh || echo "(пропущено)"` — то есть при любой
#     заминке с копией молча шёл дальше и обновлял сервис БЕЗ резервной копии;
#   • тянул код через `git pull` без указания ветки — на сервере с отвязанной
#     веткой это либо ошибка, либо чужой код;
#   • не проверял ни место на диске, ни что схема базы вообще применилась.
#
# Основной скрипт всё это делает и умеет откат. Поэтому здесь только переход.
# ─────────────────────────────────────────────────────────────────────────────
set -euo pipefail
exec bash "$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/scripts/deploy.sh" "$@"
